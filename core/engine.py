import json
import re
from pathlib import Path
from datetime import datetime, timezone, timedelta
from typing import Dict, List, Optional, Tuple, Any

# In-memory cache for parsed files: path -> (mtime, size, byte_offset, stats, line_records, first_prompt)
_FILE_CACHE: Dict[str, Tuple[float, int, int, Dict[str, int], List[Tuple[Optional[datetime], int, int, int]], str]] = {}


def estimate_tokens(text: str) -> int:
    """Estimates Gemini token count using the standard ~4 chars/token heuristic."""
    if not text:
        return 0
    return max(1, round(len(text) / 4))


def parse_iso_time(ts_str: Optional[str]) -> Optional[datetime]:
    """Parses ISO timestamp strings into UTC datetime objects."""
    if not ts_str:
        return None
    try:
        ts_str = ts_str.replace("Z", "+00:00")
        return datetime.fromisoformat(ts_str)
    except Exception:
        return None


def extract_first_prompt(data: dict) -> Optional[str]:
    """Extracts a short snippet of the first user prompt to use as a human-readable session title."""
    source = str(data.get("source", "")).upper()
    step_type = str(data.get("type", "")).upper()
    if source in ("USER", "USER_EXPLICIT") or "USER" in step_type:
        content = data.get("content", "")
        if isinstance(content, str):
            clean = " ".join(content.replace("\r", " ").replace("\n", " ").split()).strip()
            if clean:
                return clean[:70] + ("..." if len(clean) > 70 else "")
    return None


def extract_line_tokens(data: dict) -> Tuple[int, int, int]:
    """Extracts (prompt_toks, thinking_toks, candidate_toks) from a single transcript line."""
    source = str(data.get("source", "")).upper()
    step_type = str(data.get("type", "")).upper()
    content = data.get("content", "")
    thinking_content = data.get("thinking", "")
    tool_calls = data.get("tool_calls", [])

    prompt_toks = 0
    thinking_toks = 0
    candidate_toks = 0

    if thinking_content:
        thinking_toks += estimate_tokens(thinking_content)

    text_pieces = []
    if isinstance(content, str):
        text_pieces.append(content)
    elif isinstance(content, (dict, list)):
        text_pieces.append(json.dumps(content))

    full_text = "\n".join(text_pieces).strip()
    if full_text:
        thought_matches = re.findall(r"<(?:thought|thinking)>(.*?)</(?:thought|thinking)>", full_text, flags=re.DOTALL)
        for thought in thought_matches:
            thinking_toks += estimate_tokens(thought)

        cleaned_text = re.sub(r"<(?:thought|thinking)>.*?</(?:thought|thinking)>", "", full_text, flags=re.DOTALL).strip()
        tokens = estimate_tokens(cleaned_text)

        if step_type == "PLANNER_RESPONSE":
            candidate_toks += tokens
        elif step_type in ("USER_INPUT", "CHECKPOINT", "SYSTEM_INSTRUCTIONS") or source in ("USER", "USER_EXPLICIT", "SYSTEM"):
            prompt_toks += tokens
        elif step_type == "GENERIC":
            # Tool execution output returned from environment into the model's context
            prompt_toks += tokens
        elif source == "MODEL":
            candidate_toks += tokens
        else:
            prompt_toks += tokens

    if tool_calls:
        # Tool call invocations generated by the model are candidate/output tokens
        candidate_toks += estimate_tokens(json.dumps(tool_calls))

    return prompt_toks, thinking_toks, candidate_toks


def parse_transcript_file_cached(file_path: Any) -> Tuple[Dict[str, int], List[Tuple[Optional[datetime], int, int, int]], str]:
    """
    Parses a transcript file incrementally with caching based on file modification time and byte offset.
    Only parses newly appended lines on updates for lightning-fast 0.0% CPU overhead.
    """
    if not file_path:
        return {"prompt": 0, "candidates": 0, "thinking": 0}, [], ""
    file_path = Path(file_path)
    file_key = str(file_path.resolve())
    try:
        stat = file_path.stat()
        mtime, size = stat.st_mtime, stat.st_size
    except (OSError, ValueError):
        return {"prompt": 0, "candidates": 0, "thinking": 0}, [], ""

    cached_mtime, cached_size, cached_offset = 0.0, 0, 0
    stats = {"prompt": 0, "candidates": 0, "thinking": 0}
    line_records: List[Tuple[Optional[datetime], int, int, int]] = []
    first_prompt = ""

    if file_key in _FILE_CACHE:
        cached_mtime, cached_size, cached_offset, cached_stats, cached_records, cached_prompt = _FILE_CACHE[file_key]
        if cached_mtime == mtime and cached_size == size:
            return cached_stats.copy(), list(cached_records), cached_prompt
        # If file grew and offset is valid, incrementally read new bytes
        if size >= cached_offset and cached_offset > 0:
            stats = cached_stats.copy()
            line_records = list(cached_records)
            first_prompt = cached_prompt
        else:
            cached_offset = 0

    new_offset = cached_offset
    try:
        with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
            if cached_offset > 0:
                f.seek(cached_offset)
            for line in f:
                line_str = line.strip()
                if not line_str:
                    continue
                try:
                    data = json.loads(line_str)
                    if isinstance(data, dict):
                        if not first_prompt:
                            fp = extract_first_prompt(data)
                            if fp:
                                first_prompt = fp
                        ts = parse_iso_time(data.get("created_at"))
                        p, th, c = extract_line_tokens(data)
                        stats["prompt"] += p
                        stats["thinking"] += th
                        stats["candidates"] += c
                        line_records.append((ts, p, th, c))
                except json.JSONDecodeError:
                    continue
            new_offset = f.tell()
    except Exception:
        pass

    # Prune old cache entries if cache reaches maximum limit
    if len(_FILE_CACHE) >= 200 and file_key not in _FILE_CACHE:
        oldest_keys = list(_FILE_CACHE.keys())[:50]
        for k in oldest_keys:
            _FILE_CACHE.pop(k, None)

    _FILE_CACHE[file_key] = (mtime, size, new_offset, stats.copy(), line_records, first_prompt)
    return stats, line_records, first_prompt


def calculate_window_tracker(line_records: List[Tuple[Optional[datetime], int, int, int]], ref_time: Optional[datetime] = None) -> Dict[str, Any]:
    """Calculates 5h, 7d, and short-window burn velocity breakdowns from parsed line records."""
    now = ref_time if ref_time is not None else datetime.now(timezone.utc)
    if now.tzinfo is None:
        now = now.replace(tzinfo=timezone.utc)

    from datetime import timedelta
    cutoff = now - timedelta(days=7, hours=1)
    line_records = [r for r in line_records if r[0] is None or r[0] >= cutoff]

    window_tracker = {
        "tokens_5h": 0,
        "prompt_5h": 0,
        "thinking_5h": 0,
        "candidates_5h": 0,
        "oldest_5h_time": None,

        "tokens_7d": 0,
        "prompt_7d": 0,
        "thinking_7d": 0,
        "candidates_7d": 0,
        "oldest_7d_time": None,

        "tokens_15m": 0,
        "tokens_1h": 0,
    }

    fifteen_mins_ago = now - timedelta(minutes=15)
    one_hour_ago = now - timedelta(hours=1)
    five_hours_ago = now - timedelta(hours=5)
    seven_days_ago = now - timedelta(days=7)

    for ts, p, th, c in line_records:
        total_line = p + th + c
        if total_line <= 0 or ts is None:
            continue

        if ts.tzinfo is None:
            ts = ts.replace(tzinfo=timezone.utc)

        # 15-Min & 1-Hour Burn Velocity
        if ts >= fifteen_mins_ago:
            window_tracker["tokens_15m"] += total_line
        if ts >= one_hour_ago:
            window_tracker["tokens_1h"] += total_line

        # 5-Hour Window
        if ts >= five_hours_ago:
            window_tracker["tokens_5h"] += total_line
            window_tracker["prompt_5h"] += p
            window_tracker["thinking_5h"] += th
            window_tracker["candidates_5h"] += c
            if window_tracker["oldest_5h_time"] is None or ts < window_tracker["oldest_5h_time"]:
                window_tracker["oldest_5h_time"] = ts

        # 7-Day Window
        if ts >= seven_days_ago:
            window_tracker["tokens_7d"] += total_line
            window_tracker["prompt_7d"] += p
            window_tracker["thinking_7d"] += th
            window_tracker["candidates_7d"] += c
            if window_tracker["oldest_7d_time"] is None or ts < window_tracker["oldest_7d_time"]:
                window_tracker["oldest_7d_time"] = ts

    return window_tracker


def format_recovery_info(window_tracker: Dict[str, Any], ref_time: Optional[datetime] = None) -> Dict[str, Any]:
    """Formats human-readable recovery info, percentages, countdowns, and window-scoped token breakdowns."""
    now = ref_time if ref_time is not None else datetime.now(timezone.utc)
    if now.tzinfo is None:
        now = now.replace(tzinfo=timezone.utc)

    # 5-Hour Window formatting
    reset_5h_str = "No recent usage"
    pct_5h = 0.0
    secs_5h = 0
    recovery_5h_dt = None

    if window_tracker["oldest_5h_time"]:
        oldest_5h = window_tracker["oldest_5h_time"]
        if oldest_5h.tzinfo is None:
            oldest_5h = oldest_5h.replace(tzinfo=timezone.utc)
        recovery_5h_dt = oldest_5h + timedelta(hours=5)
        secs_5h = max(0, int((recovery_5h_dt - now).total_seconds()))
        pct_5h = (secs_5h / (5 * 3600)) * 100
        mins_remaining = secs_5h // 60
        hours = mins_remaining // 60
        mins = mins_remaining % 60
        if secs_5h > 0:
            reset_5h_str = f"in {hours}h {mins:02d}m ({pct_5h:.1f}% remaining)"
        else:
            reset_5h_str = "Fully recovered"

    # 7-Day Window formatting
    reset_7d_str = "No weekly usage"
    pct_7d = 0.0
    secs_7d = 0
    recovery_7d_dt = None

    if window_tracker["oldest_7d_time"]:
        oldest_7d = window_tracker["oldest_7d_time"]
        if oldest_7d.tzinfo is None:
            oldest_7d = oldest_7d.replace(tzinfo=timezone.utc)
        recovery_7d_dt = oldest_7d + timedelta(days=7)
        secs_7d = max(0, int((recovery_7d_dt - now).total_seconds()))
        pct_7d = (secs_7d / (7 * 86400)) * 100
        days_7d = secs_7d // 86400
        hours_7d = (secs_7d % 86400) // 3600
        mins_7d = (secs_7d % 3600) // 60
        if secs_7d > 0:
            if days_7d > 0:
                reset_7d_str = f"in {days_7d}d {hours_7d}h {mins_7d:02d}m ({pct_7d:.1f}% remaining)"
            else:
                reset_7d_str = f"in {hours_7d}h {mins_7d:02d}m ({pct_7d:.1f}% remaining)"
        else:
            reset_7d_str = "Fully recovered"

    toks_15m = window_tracker.get("tokens_15m", 0)
    toks_1h = window_tracker.get("tokens_1h", 0)
    burn_rate_hr = toks_15m * 4 if toks_15m > 0 else toks_1h
    burn_rate_str = f"{burn_rate_hr:,} tok/hr" if burn_rate_hr > 0 else "Idle"

    return {
        "tokens_15m": toks_15m,
        "tokens_1h": toks_1h,
        "burn_rate_hr": burn_rate_hr,
        "burn_rate_str": burn_rate_str,

        "tokens_5h": window_tracker["tokens_5h"],
        "prompt_5h": window_tracker["prompt_5h"],
        "thinking_5h": window_tracker["thinking_5h"],
        "candidates_5h": window_tracker["candidates_5h"],
        "reset_5h_str": reset_5h_str,
        "pct_5h_remaining": pct_5h,
        "secs_5h_remaining": secs_5h,
        "recovery_5h_time": recovery_5h_dt,

        "tokens_7d": window_tracker["tokens_7d"],
        "prompt_7d": window_tracker["prompt_7d"],
        "thinking_7d": window_tracker["thinking_7d"],
        "candidates_7d": window_tracker["candidates_7d"],
        "reset_7d_str": reset_7d_str,
        "pct_7d_remaining": pct_7d,
        "secs_7d_remaining": secs_7d,
        "recovery_7d_time": recovery_7d_dt,
    }


