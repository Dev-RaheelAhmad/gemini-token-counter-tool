def get_session_user_report(
    session: Optional[Dict],
    target_user: str,
    active_account: str,
    ref_time: Optional[datetime] = None
) -> Dict[str, Any]:
    """
    Generates a token report for a specific user scoped strictly to a single session.
    If the session contains tokens for this user, returns that user's token metrics.
    If the user has no tokens in this session, returns an empty zeroed report.
    """
    if not session:
        return get_empty_session_report(session_id="No Active Session", title="No Active Session")

    sid = session.get("session_id", "")
    target_clean = (target_user or "").strip().lower()
    active_clean = (active_account or "").strip().lower()

    # 1. Check if ledger has specific account_usage breakdown for this session
    try:
        from core.ledger import ledger
        ledger_sess = ledger.sessions.get(sid)
        if ledger_sess:
            acc_usage = ledger_sess.get("account_usage", {})
            if isinstance(acc_usage, dict):
                for act_k, udata in acc_usage.items():
                    k_clean = act_k.strip().lower()
                    is_default = not k_clean or k_clean in ("default", "local", "default / local account")
                    match = (
                        not target_clean
                        or (target_clean in ("active", "active user") and (k_clean == active_clean or is_default))
                        or k_clean == target_clean
                        or (target_clean in ("default", "local", "default / local account") and is_default)
                        or (target_clean == active_clean and is_default)
                        or ('@' in k_clean and target_clean == k_clean.split('@')[0])
                    )
                    if match and udata.get("total", 0) > 0:
                        p = udata.get("prompt", 0)
                        th = udata.get("thinking", 0)
                        c = udata.get("candidates", 0)
                        tot = p + th + c
                        recs = udata.get("records", [])
                        window_tracker = calculate_window_tracker(recs, ref_time=ref_time)
                        recovery = format_recovery_info(window_tracker, ref_time=ref_time)
                        fp = ledger_sess.get("first_prompt") or session.get("first_prompt") or sid
                        return {
                            "is_all": False,
                            "mode": "session",
                            "session_id": sid,
                            "title": fp,
                            "first_prompt": fp,
                            "account": act_k,
                            "folder": str(session.get("folder", "")),
                            "file": str(session.get("file", "")),
                            "last_active": session.get("last_active_str", "Unknown"),
                            "mtime": session.get("mtime", 0),
                            "size": session.get("size", 0),
                            "prompt": p,
                            "thinking": th,
                            "candidates": c,
                            "total": tot,
                            "prompt_pct": (p / tot * 100) if tot > 0 else 0.0,
                            "thinking_pct": (th / tot * 100) if tot > 0 else 0.0,
                            "candidates_pct": (c / tot * 100) if tot > 0 else 0.0,
                            **recovery,
                        }
    except Exception:
        pass

    # 2. Fallback to session-level account matching
    sess_acc = session.get("account", "").strip()
    if not sess_acc or sess_acc in ("Default", "Local", "None", "Unassigned"):
        try:
            from core.ledger import ledger
            locked_acc = ledger.get_session_account(sid)
            if locked_acc:
                sess_acc = locked_acc
        except Exception:
            pass

    if not sess_acc:
        sess_acc = active_account or "Default"

    # Determine match: 'active' matches the active_account or default/local
    is_match = False
    if target_clean in ("active", "active user"):
        if sess_acc.lower() == active_clean or sess_acc in ("Default", "Local", ""):
            is_match = True
    elif target_clean:
        if sess_acc.lower() == target_clean:
            is_match = True
        elif sess_acc in ("Default", "Local", "") and target_clean == active_clean:
            is_match = True
        elif '@' in sess_acc and target_clean == sess_acc.split('@')[0].lower():
            is_match = True

    if is_match:
        return get_single_session_report(session, ref_time=ref_time, account_email=target_user)
    else:
        return get_empty_session_report(
            session_id=session.get("session_id", "N/A"),
            title=session.get("first_prompt") or session.get("session_id", "N/A"),
            account_email=target_user
        )


def get_single_session_report(session: Dict, ref_time: Optional[datetime] = None, account_email: str = "") -> Dict[str, Any]:
    """Generates complete token analysis and rate limit stats for a single session."""
    stats, records, first_prompt = parse_transcript_file_cached(session["file"])
    window_tracker = calculate_window_tracker(records, ref_time=ref_time)
    recovery = format_recovery_info(window_tracker, ref_time=ref_time)

    prompt = stats["prompt"]
    thinking = stats["thinking"]
    candidates = stats["candidates"]
    total = prompt + thinking + candidates

    prompt_pct = (prompt / total * 100) if total > 0 else 0.0
    thinking_pct = (thinking / total * 100) if total > 0 else 0.0
    candidates_pct = (candidates / total * 100) if total > 0 else 0.0

    # Sync into in-memory ledger
    try:
        from core.ledger import ledger
        from core.account_manager import is_valid_account_email
        force_acc = bool(account_email and is_valid_account_email(account_email))
        ledger.update_session(
            session_id=session.get("session_id", "unknown"),
            account_email=account_email or "Default",
            stats=stats,
            line_records=records,
            first_prompt=first_prompt,
            last_active=session.get("last_active_str", "Unknown"),
            mtime=session.get("mtime", 0.0),
            size=session.get("size", 0),
            force_account=force_acc
        )
    except Exception:
        pass

    return {
        "is_all": False,
        "mode": "session",
        "session_id": session.get("session_id", "unknown"),
        "title": first_prompt or session.get("session_id", "unknown"),
        "first_prompt": first_prompt,
        "folder": str(session.get("folder", "")),
        "file": str(session.get("file", "")),
        "last_active": session.get("last_active_str", "Unknown"),
        "mtime": session.get("mtime", 0),
        "size": session.get("size", 0),
        "prompt": prompt,
        "thinking": thinking,
        "candidates": candidates,
        "total": total,
        "prompt_pct": prompt_pct,
        "thinking_pct": thinking_pct,
        "candidates_pct": candidates_pct,
        **recovery,
    }


def get_active_account_report(account_email: str, sessions: Optional[List[Dict]] = None, ref_time: Optional[datetime] = None) -> Dict[str, Any]:
    """Generates rolling rate limit stats strictly for the active Google account from the in-memory ledger."""
    try:
        from core.ledger import ledger
        # If sessions provided, ensure they are registered in ledger
        if sessions:
            for s in sessions:
                stats, records, fp = parse_transcript_file_cached(s["file"])
                ledger.update_session(
                    session_id=s.get("session_id", "unknown"),
                    account_email=account_email or "Default",
                    stats=stats,
                    line_records=records,
                    first_prompt=fp,
                    last_active=s.get("last_active_str", "Unknown"),
                    mtime=s.get("mtime", 0.0),
                    size=s.get("size", 0)
                )
        return ledger.get_account_report(account_email=account_email, ref_time=ref_time)
    except Exception:
        return get_all_sessions_report(sessions or [], ref_time=ref_time)


def get_all_sessions_report(sessions: List[Dict], ref_time: Optional[datetime] = None) -> Dict[str, Any]:
    """Generates cumulative token analysis and rate limit stats across all sessions and syncs to ledger."""
    total_prompt = 0
    total_thinking = 0
    total_candidates = 0
    all_records: List[Tuple[Optional[datetime], int, int, int]] = []
    active_sessions_count = 0

    try:
        from core.ledger import ledger
        from core.account_manager import get_active_google_account
        active_acc = get_active_google_account() or "Default"
    except Exception:
        ledger = None
        active_acc = "Default"

    for idx, s in enumerate(sessions):
        stats, records, fp = parse_transcript_file_cached(s["file"])
        s_total = sum(stats.values())
        if s_total > 0:
            total_prompt += stats["prompt"]
            total_thinking += stats["thinking"]
            total_candidates += stats["candidates"]
            all_records.extend(records)
            active_sessions_count += 1

        if ledger:
            sid = s.get("session_id", "unknown")
            existing_acc = ledger.get_session_account(sid)
            if idx == 0 and active_acc and active_acc not in ("Default", "Local"):
                sess_acc = active_acc
                force_acc = True
            elif not existing_acc or existing_acc in ("Default", "Local", "None", "Unassigned"):
                sess_acc = active_acc
                force_acc = False
            else:
                sess_acc = existing_acc
                force_acc = False
            ledger.update_session(
                session_id=sid,
                account_email=sess_acc,
                stats=stats,
                line_records=records,
                first_prompt=fp,
                last_active=s.get("last_active_str", "Unknown"),
                mtime=s.get("mtime", 0.0),
                size=s.get("size", 0),
                folder_path=str(s.get("folder", "")),
                file_path=str(s.get("file", "")),
                force_account=force_acc
            )
            s["tokens"] = s_total
            s["account"] = sess_acc

    grand_total = total_prompt + total_thinking + total_candidates
    window_tracker = calculate_window_tracker(all_records, ref_time=ref_time)
    recovery = format_recovery_info(window_tracker, ref_time=ref_time)

    prompt_pct = (total_prompt / grand_total * 100) if grand_total > 0 else 0.0
    thinking_pct = (total_thinking / grand_total * 100) if grand_total > 0 else 0.0
    candidates_pct = (total_candidates / grand_total * 100) if grand_total > 0 else 0.0

    return {
        "is_all": True,
        "mode": "device",
        "session_id": f"All Sessions ({active_sessions_count} active)",
        "unique_sessions_count": active_sessions_count,
        "total_sessions_found": len(sessions),
        "prompt": total_prompt,
        "thinking": total_thinking,
        "candidates": total_candidates,
        "total": grand_total,
        "prompt_pct": prompt_pct,
        "thinking_pct": thinking_pct,
        "candidates_pct": candidates_pct,
        **recovery,
    }
